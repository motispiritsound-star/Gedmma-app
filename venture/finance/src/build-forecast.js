#!/usr/bin/env node
import { writeFileSync } from 'node:fs';
import { v } from './economics.js';
import { forecast, formatForecast, BUDGET_SCENARIOS, SUBSCRIPTION_CONTRIBUTION_MARGIN } from './forecast.js';
import { sourcingSpecification } from './required-to-believe.js';
import { starterSet, CAC_COLD } from './product-spec.js';

const spec = starterSet(79, 18);


// Derive the ceiling rather than restating it, so this document cannot drift out
// of step with the economics engine when a cost input changes.
const CEILING = sourcingSpecification(
  starterSet(79, 0),
  { plannedCac: CAC_COLD },
).maxUnitCost;

const shared = { months: 12, cacInflation: 1.02, subscriptionValue: 20, fixedMonthlyCost: 450 };
const spend = (arr) => [...arr, ...Array(12 - arr.length).fill(arr.at(-1))];

const SCENARIOS = {
  Downside: { ...shared, adSpend: spend(BUDGET_SCENARIOS.standard.monthlyAdSpend),
    cac: 38, organicOrders: 4,  organicGrowth: 1.05, subscriptionTakeRate: 0.12, monthlyChurn: 0.15 },
  Base:     { ...shared, adSpend: spend(BUDGET_SCENARIOS.standard.monthlyAdSpend),
    cac: 27, organicOrders: 10, organicGrowth: 1.12, subscriptionTakeRate: 0.25, monthlyChurn: 0.08 },
  Upside:   { ...shared, adSpend: spend(BUDGET_SCENARIOS.standard.monthlyAdSpend),
    cac: 20, organicOrders: 18, organicGrowth: 1.20, subscriptionTakeRate: 0.40, monthlyChurn: 0.05 },
};

const results = Object.entries(SCENARIOS).map(([k, a]) => [k, forecast(spec, a), a]);

// The base case looks comfortable largely because the landed cost was assumed
// generously. Re-run it at the sourcing ceiling to show how thin the margin for
// error on that single unverified number really is.
const atCeiling = forecast(
  { ...spec, unitCost: v(CEILING, 'UNVERIFIED', 'the sourcing ceiling from unit-economics.md') },
  SCENARIOS.Base,
);

const out = `# Financial forecast

Generated by \`venture/finance/src/build-forecast.js\`. Regenerate: \`node src/build-forecast.js\`.

## This is a model, not a prediction

Every input below is \`ASSUMPTION\` or \`UNVERIFIED\`. **No supplier has quoted, no
retail price has been observed, no advertising has run, and no customer has
subscribed to anything.** The two numbers that drive the entire result — CAC and
subscription retention — are exactly the two that cannot be known before launch.

So do not read the tables as forecasts of what will happen. Read them as: *if
these assumptions held, this is the arithmetic that follows.* Their value is in
the shape and the sensitivity, not the totals.

The honest use of this document is to answer two questions: **how much cash does
this need before it turns**, and **which assumption would hurt most if wrong**.

## Inputs common to all three scenarios

| Input | Value | Provenance |
|---|---|---|
| Starter set price (incl. VAT) | EUR 79 | **UNVERIFIED** — no NL retail price observed |
| Landed cost of the set | EUR 18 | **UNVERIFIED** — no supplier contacted; sits under the EUR ${CEILING.toFixed(2)} ceiling but is not a quote |
| Subscription contribution per renewal | EUR ${(20 * SUBSCRIPTION_CONTRIBUTION_MARGIN).toFixed(2)} | ASSUMPTION (EUR 20 at ${(SUBSCRIPTION_CONTRIBUTION_MARGIN * 100).toFixed(0)}% margin) |
| Fixed monthly cost | EUR 450 | ASSUMPTION — platform, apps, tools. **Shopify pricing could not be verified; shopify.com is blocked** |
| CAC inflation | 2% per month | ASSUMPTION, directionally supported by reported CPM rises |
| Ad spend | Standard budget scenario | See below |

## What separates the scenarios

| | Downside | Base | Upside |
|---|---:|---:|---:|
| Blended CAC (month 1) | EUR 38 | EUR 27 | EUR 20 |
| Organic orders (month 1) | 4 | 10 | 18 |
| Organic growth / month | 5% | 12% | 20% |
| Subscription take rate | 12% | 25% | 40% |
| Monthly subscriber churn | 15% | 8% | 5% |

The spread between scenarios is driven almost entirely by **subscription take
rate and churn**, not by advertising. That is the model telling you where the
business actually lives.

${results.map(([k, r]) => formatForecast(r, k)).join('\n\n')}

## Reading the results

| Scenario | First profitable month | Cash required (deepest trough) | Cumulative at month 12 |
|---|---|---:|---:|
${results.map(([k, r]) => `| ${k} | ${r.breakEvenMonth ?? '**never**'} | EUR ${Math.abs(Math.min(0, r.cashTrough)).toFixed(0)} | EUR ${r.finalCumulative.toFixed(0)} |`).join('\n')}

### The base case is not as comfortable as it looks

Base turns profitable immediately — but only because the landed cost was assumed
at EUR 18. That number is **UNVERIFIED**: no supplier has quoted it. Re-running
the identical base case with the cost at the EUR ${CEILING.toFixed(2)} ceiling from
*../strategy/unit-economics.md*:

| | Base @ EUR 18 cost | Base @ EUR ${CEILING.toFixed(2)} ceiling |
|---|---:|---:|
| First profitable month | ${results[1][1].breakEvenMonth ?? 'never'} | ${atCeiling.breakEvenMonth ?? '**never**'} |
| Cash required | EUR ${Math.abs(Math.min(0, results[1][1].cashTrough)).toFixed(0)} | EUR ${Math.abs(Math.min(0, atCeiling.cashTrough)).toFixed(0)} |
| Cumulative at month 12 | EUR ${results[1][1].finalCumulative.toFixed(0)} | EUR ${atCeiling.finalCumulative.toFixed(0)} |

A EUR ${(CEILING - 18).toFixed(2)} difference in the cost of one product — well inside the range a single
supplier negotiation moves — swings the twelve-month position by
EUR ${(results[1][1].finalCumulative - atCeiling.finalCumulative).toFixed(0)}.
**This is why the RFQ comes before the ad account.**

**The cash trough matters more than the profit line.** It is the money that must
exist before revenue arrives, and it is the number that kills undercapitalised
stores that were otherwise going to work.

## Budget scenarios

${Object.values(BUDGET_SCENARIOS).map((b) => `**${b.label}** — 6-month ad spend EUR ${b.monthlyAdSpend.reduce((a, c) => a + c, 0).toLocaleString('en-GB')}\n\n> ${b.purpose}\n`).join('\n')}

The sequencing rule: **do not move to Accelerated on modelled assumptions.** Move
only once contribution margin and repeat rate have been *measured*. The purpose
of the first budget is to buy information, and information bought cheaply is the
only genuinely good deal available at this stage.

## The sensitivity that decides everything

Compare Downside and Upside. Same product, same price, same ad budget. The
difference is whether players resubscribe for grips.

**If the subscription does not retain, this is a one-shot bag business buying
expensive traffic — which is precisely the model the strategy was built to
avoid.** The single most valuable early experiment is therefore not an ad test.
It is finding out whether the replenishment offer is taken up and renewed.
`;

writeFileSync(new URL('../forecast.md', import.meta.url), out);
results.forEach(([k, r]) => console.log(`${k.padEnd(9)} breakeven month ${String(r.breakEvenMonth ?? 'never').padStart(5)}  trough EUR ${r.cashTrough.toFixed(0).padStart(7)}  m12 EUR ${r.finalCumulative.toFixed(0).padStart(8)}`));
