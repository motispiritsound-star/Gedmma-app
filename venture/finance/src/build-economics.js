#!/usr/bin/env node
/** Generates strategy/unit-economics.md for the selected concept. */
import { writeFileSync } from 'node:fs';
import { v, computeOrderEconomics, computeAcquisitionTargets, computeLifetimeValue, computeReturnOnAcquisition } from './economics.js';
import { runStressSuite, evaluateGates, formatSuiteMarkdown } from './stress.js';
import { sourcingSpecification, priceLadder } from './required-to-believe.js';
import { starterSet as set, CAC_COLD, CAC_BLENDED } from './product-spec.js';



const PRICES = [39, 49, 59, 69, 79, 89, 99];
const ladderCold = priceLadder(set(0), PRICES, { plannedCac: CAC_COLD });
const ladderBlend = priceLadder(set(0), PRICES, { plannedCac: CAC_BLENDED });

const HEADLINE = 79;
const spec = sourcingSpecification(set(HEADLINE), { plannedCac: CAC_COLD, requiredFirstOrderProfit: 0 });
const specProfit = sourcingSpecification(set(HEADLINE), { plannedCac: CAC_COLD, requiredFirstOrderProfit: 8 });

// Stress the concept AT the sourcing ceiling — the marginal case.
const atCeiling = { ...set(HEADLINE), unitCost: v(spec.maxUnitCost, 'UNVERIFIED', 'the sourcing ceiling, not a quote') };
const suite = runStressSuite(atCeiling, { plannedCac: CAC_COLD });
const gates = evaluateGates(suite);

const order = computeOrderEconomics(atCeiling);
const ltv = computeLifetimeValue(order, {
  repeatOrdersPerYear: v(2.5, 'ASSUMPTION', 'grip replenishment cadence — the core retention claim, untested'),
  retentionRate: v(0.35, 'ASSUMPTION', 'deliberately pessimistic for a new brand'),
});
const roa = computeReturnOnAcquisition(ltv, CAC_COLD);

const eur = (x) => `EUR ${x.toFixed(2)}`;
const pct = (x) => `${(x * 100).toFixed(1)}%`;

const out = `# Unit economics — padel starter set

Generated by \`venture/finance/src/build-economics.js\`. Regenerate after changing
any input: \`node src/build-economics.js\`.

## Every number here is INDICATIVE. Read this first.

**No supplier has been contacted and no retail price has been observed.** The
price band could not be checked because no retailer page could be opened from
this environment (\`ACCESS-AND-LIMITS.md\`). The economics engine therefore
returns:

> ${gates.verdict}

So this document does **not** claim the business is profitable. It does something
more useful given the missing data: it states **what would have to be true**.

## The question inverted

Rather than invent a supplier cost and compute a flattering margin, the model
solves for the cost ceiling. The output is a sourcing brief and a kill criterion
in one number.

**At a ${eur(HEADLINE)} starter set and a ${eur(CAC_COLD)} cold-traffic CAC:**

> ${spec.statement}

Allowing ${eur(8)} of first-order profit rather than bare breakeven tightens this to
**${eur(specProfit.maxUnitCost)}**.

That is the number to put on an RFQ. A quote above it is not a negotiation, it is
a no.

At the ceiling the order carries a ${pct(spec.grossMarginAtCeiling)} gross margin and a
${pct(spec.contributionMarginAtCeiling)} pre-ad contribution margin, implying a break-even ROAS of
**${spec.breakEvenRoasAtCeiling.toFixed(2)}x** on VAT-inclusive reported revenue.

## How high does the price have to be?

Maximum landed cost of the complete set, by retail price. Where a row is not
achievable, the order cannot fund its own acquisition even if the goods were free.

| Retail (incl. VAT) | Max landed cost @ ${eur(CAC_COLD)} CAC | Max landed cost @ ${eur(CAC_BLENDED)} CAC |
|---:|---:|---:|
${PRICES.map((p, i) => {
  const c = ladderCold[i], b = ladderBlend[i];
  return `| ${eur(p)} | ${c.achievable ? eur(c.maxUnitCost) : '**not achievable**'} | ${b.achievable ? eur(b.maxUnitCost) : '**not achievable**'} |`;
}).join('\n')}

**This table is the most decision-relevant output in the project.** It says the
entry price cannot sit at the bottom of the category. A ${eur(39)} order cannot fund a
cold-traffic acquisition at all, and a ${eur(49)} one leaves almost nothing to source
with. The set exists precisely to lift the order above that floor — which is why
the benchmark finding that winners default to a set rather than a unit is an
economic necessity here, not a merchandising preference.

## Stress test at the sourcing ceiling

The marginal case: a supplier quoting exactly at the ceiling, so first-order
profit is zero by construction and every shock pushes it negative.

${formatSuiteMarkdown(suite)}

Fragile under: ${gates.fragileUnder.length ? gates.fragileUnder.join('; ') : 'nothing'}.
Compound shock survived: ${gates.compoundSurvives ? 'yes' : 'no'}.

**Read this correctly.** Every shock fails because the ceiling is defined as
break-even. The table's value is the *magnitude* of each failure: it shows how
much headroom a quote must come in under the ceiling to leave a business that
survives a bad quarter. A quote at ${eur(spec.maxUnitCost)} is not a viable
business; it is the point at which the business stops existing.

## Repeat purchase — the load-bearing assumption

The entire thesis rests on grip replenishment carrying the economics, because
cold paid social alone does not.

| | |
|---|---:|
| First-order contribution | ${eur(ltv.firstOrderContribution)} |
| Lifetime contribution (2 yr, discounted, 35% retention) | ${eur(ltv.lifetimeContribution)} |
| Share of value from repeat purchase | ${pct(ltv.repeatShare)} |
| LTV:CAC at ${eur(CAC_COLD)} | ${roa.ltvToCac.toFixed(2)}x |
| First order pays back on its own | ${roa.paybackOnFirstOrder ? 'yes' : '**no**'} |

The retention inputs are **ASSUMPTION**, chosen pessimistically. They are the
least evidenced and most consequential numbers in this project: if padel players
do not in fact resubscribe for grips, the business is a one-shot bag seller
buying expensive traffic, and the thesis fails.

**Note what the model refuses to do.** It reports an LTV:CAC above 1 alongside a
first order that does not pay back, rather than netting them into one comfortable
figure. Disguising weak first-order economics behind projected lifetime value is
the specific failure the brief warned against (§8), and it is the reason both
numbers are shown.

## What must be established before any of this means anything

1. **Observed retail prices** for padel bags and grips at Dutch retailers. Free,
   fastest, and it sets the whole ladder.
2. **Supplier quotes** against the ceiling above, at a fundable MOQ.
3. **A real CAC**, which only a live test produces. The ${eur(CAC_COLD)} figure is derived
   from published Dutch Meta CPM ranges with assumed CTR and conversion — it is
   the single largest uncertainty in the model.
4. **Evidence that grip replenishment actually repeats.**
`;

writeFileSync(new URL('../../strategy/unit-economics.md', import.meta.url), out);
console.log(spec.statement);
console.log(`With EUR 8 profit: ${specProfit.maxUnitCost.toFixed(2)}`);
console.log(`\nLadder @ cold CAC:`);
ladderCold.forEach((r) => console.log(`  EUR ${String(r.priceInclVat).padStart(3)} -> ${r.achievable ? 'max cost EUR ' + r.maxUnitCost.toFixed(2) : 'NOT ACHIEVABLE'}`));
console.log(`\nLTV:CAC ${roa.ltvToCac.toFixed(2)}x, first-order payback: ${roa.paybackOnFirstOrder}`);
