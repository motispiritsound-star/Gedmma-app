const DICTIONARIES: Record<Locale, Record<Key, string>> = { nl, en };

export type TranslateKey = Key;
export type Translate = (key: Key, vars?: Record<string, string | number>) => string;

/** Builds a `t()` for a locale. Unknown placeholders are left untouched. */
export function translator(locale: Locale): Translate {
  const table = DICTIONARIES[locale];
  return (key, vars) => {
    const template = table[key] ?? DICTIONARIES.en[key] ?? key;
    if (!vars) return template;
    return template.replace(/\{(\w+)\}/g, (match, name: string) =>
      name in vars ? String(vars[name]) : match,
    );
  };
}
